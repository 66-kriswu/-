/**
  * @brief  This function is executed in case of error occurrence.
  * @retval None
  */
void Error_Handler(void)
{
  /* USER CODE BEGIN Error_Handler_Debug */
  /* A silent infinite loop is useless for field diagnosis: with no LED and no
     UART it is indistinguishable from a board with no power at all.
     This handler therefore drives a fast ~10 Hz blink on PC13 (on board LED)
     and PE0 (heartbeat LED) so the three states are always distinguishable:

       both LEDs dark, nothing blinking -> board not powered / not running
       PC13 + PE0 blinking at ~10 Hz    -> firmware reached Error_Handler
       PE0 alone blinking at 2 Hz       -> firmware is running normally

     The GPIO clocks are enabled here because Error_Handler() can be reached
     before MX_GPIO_Init(), for instance when the HSE crystal does not start or
     the PLL does not lock in SystemClock_Config(). */
  __disable_irq();

  __HAL_RCC_GPIOC_CLK_ENABLE();
  __HAL_RCC_GPIOE_CLK_ENABLE();

  {
    GPIO_InitTypeDef gpio = {0};

    gpio.Mode  = GPIO_MODE_OUTPUT_PP;
    gpio.Pull  = GPIO_NOPULL;
    gpio.Speed = GPIO_SPEED_FREQ_LOW;

    gpio.Pin = GPIO_PIN_13;                 /* PC13, on board LED   */
    HAL_GPIO_Init(GPIOC, &gpio);

    gpio.Pin = GPIO_PIN_0;                  /* PE0,  heartbeat LED  */
    HAL_GPIO_Init(GPIOE, &gpio);
  }

  for (;;)
  {
    HAL_GPIO_TogglePin(GPIOC, GPIO_PIN_13);
    HAL_GPIO_TogglePin(GPIOE, GPIO_PIN_0);

    for (volatile uint32_t spin = 0u; spin < 400000u; spin++)
    {
      __NOP();
    }
  }
  /* USER CODE END Error_Handler_Debug */
}

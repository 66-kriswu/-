/**
  * @brief This function handles USART2 global interrupt.
  */
/* [学习标注] USART2：先清 IDLE 标志并做判帧钩子，再交给 HAL_UART_IRQHandler。 —— 顺序不能反：HAL 不认识 IDLE，不清就会一直进中断（见 §3.5.1）。 */
void USART2_IRQHandler(void)
{
  /* USER CODE BEGIN USART2_IRQn 0 */
  /* HAL_UART_IRQHandler() does not know about the IDLE line detection flag, so
     it would never be cleared and the interrupt would fire forever.  The
     framing hook therefore has to run here, before the HAL handler.
     Section 4.7: "must be restarted" is not needed with a circular DMA, the
     frame length is derived from the DMA counter instead. */
  if (__HAL_UART_GET_FLAG(&huart2, UART_FLAG_IDLE) != RESET)
  {
    __HAL_UART_CLEAR_IDLEFLAG(&huart2);
    arm_uart_gcode_idle_isr();
  }
  /* USER CODE END USART2_IRQn 0 */
  HAL_UART_IRQHandler(&huart2);
  /* USER CODE BEGIN USART2_IRQn 1 */

  /* USER CODE END USART2_IRQn 1 */
}

/**
  * @brief This function handles USART3 global interrupt.
  */
/* [学习标注] USART3：调试口的 IDLE 判帧钩子，然后交给 HAL。 */
void USART3_IRQHandler(void)
{
  /* USER CODE BEGIN USART3_IRQn 0 */
  /* Same IDLE framing hook as USART2, for the debug link. */
  if (__HAL_UART_GET_FLAG(&huart3, UART_FLAG_IDLE) != RESET)
  {
    __HAL_UART_CLEAR_IDLEFLAG(&huart3);
    arm_uart_debug_idle_isr();
  }
  /* USER CODE END USART3_IRQn 0 */
  HAL_UART_IRQHandler(&huart3);
  /* USER CODE BEGIN USART3_IRQn 1 */

  /* USER CODE END USART3_IRQn 1 */
}

